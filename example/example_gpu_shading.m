%% Calculate the aerodynamic forces and torques for different control surface rotations

% Constants
altitude__m = 3e5;
gravitational_parameter__m3_per_s2 = 3.986e14;
radius__m = 6.378e6;

rotational_velocity_BI_B__rad_per_s = 0;
velocity_I_I__m_per_s = sqrt(gravitational_parameter__m3_per_s2 ...
                             / (radius__m + altitude__m)) * [1;0;0];
wind_velocity_I_I__m_per_s = zeros(3,1);
%[T, R] = atmosnrlmsise00(altitude__m, 0, 0, 2024, 150, 0); -> Aerospace
%toolbox
density__kg_per_m3 = 3.8e-12;% R(6);
temperature__K = 934;%T(2);
particles_mass__kg = 16 * 1.6605390689252e-27;
temperature_ratio_method = 1;
%
% Loops
num_angles = 101;
pitch_angles__rad = linspace(0, pi/2, num_angles);
aerodynamic_force_B__N = nan(3, num_angles, 2);
aerodynamic_torque_B_B__Nm = aerodynamic_force_B__N;
for k = 1:length(pitch_angles__rad)
    dir = [0; 1; 0];
    attitude_angle = pitch_angles__rad(k);
    attitude_quaternion_BI = [cos(attitude_angle/2); sin(attitude_angle/2) * dir];
    % Loop over control surfaces
    bodies_rotation_angles__rad = zeros(1,5);
    bodies_rotation_angles__rad(2:5) = pi/4;

    %cpu shading run
    [aerodynamic_force_B__N(:,k,1), ...
        aerodynamic_torque_B_B__Nm(:,k,1)] = ...
        vleoAerodynamics(attitude_quaternion_BI, ...
                                    rotational_velocity_BI_B__rad_per_s, ...
                                    velocity_I_I__m_per_s, ...
                                    wind_velocity_I_I__m_per_s, ...
                                    density__kg_per_m3, ...
                                    temperature__K, ... 
                                    particles_mass__kg, ...
                                    bodies, ...                                                       
                                    bodies_rotation_angles__rad, ...
                                    temperature_ratio_method, ...
                                    1,...
                                    struct(),...
                                    false);
    
    %gpu shading run
    [aerodynamic_force_B__N(:,k,2), ...
        aerodynamic_torque_B_B__Nm(:,k,2)] = ...
        vleoAerodynamics(attitude_quaternion_BI, ...
                                    rotational_velocity_BI_B__rad_per_s, ...
                                    velocity_I_I__m_per_s, ...
                                    wind_velocity_I_I__m_per_s, ...
                                    density__kg_per_m3, ...
                                    temperature__K, ... 
                                    particles_mass__kg, ...
                                    bodies, ...                                                       
                                    bodies_rotation_angles__rad, ...
                                    temperature_ratio_method, ...
                                    1,...
                                    struct(),...
                                    true);
end

%% Plot forces and torques
figure;
tl = tiledlayout('flow');
for k = 1:3

    if k == 1
        figure_title = 'roll torque';
    elseif k == 2
        figure_title = 'pitch torque';
    else
        figure_title = 'yaw torque';
    end

    title(tl, figure_title);
    ax1 = nexttile;
    grid on;
    hold on;
    xlabel('Pitch Angle (deg)');
    ylabel('Torque (Nm)');
    plot(ax1, rad2deg(pitch_angles__rad), aerodynamic_torque_B_B__Nm(k,:,1), 'DisplayName', 'CPU Shading');
    plot(ax1, rad2deg(pitch_angles__rad), aerodynamic_torque_B_B__Nm(k,:,2), 'DisplayName', 'GPU Shading');
    legend;
end